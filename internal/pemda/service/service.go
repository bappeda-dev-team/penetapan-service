func (s *PenetapanPemdaService) getActiveSnapshot(
	ctx context.Context,
	tahun int,
	jenisPenetapan domain.JenisPenetapan,
) (*domain.ActiveSnapshot, error) {
	snapshot, err := s.Repo.GetActiveSnapshot(ctx, tahun, jenisPenetapan)
	if err != nil {
		s.Logger.Error("ambil snapshot aktif Pemda gagal", "err", err)
		return nil, err
	}
	if snapshot == nil {
		s.Logger.WarnContext(
			ctx,
			"snapshot aktif Pemda tidak ditemukan",
			"tahun", tahun,
			"jenis_penetapan", jenisPenetapan,
		)
		return &domain.ActiveSnapshot{}, nil
	}

	return snapshot, nil
}

