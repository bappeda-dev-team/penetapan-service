func (s *PenetapanPemdaService) FindTujuanPemda(
	ctx context.Context,
	tahun int,
) (web.TujuanPenetapanPemdaResponse, error) {
	snapshot, err := s.getActiveSnapshot(ctx, tahun, domain.JenisPenetapanTujuanPemda)
	if err != nil {
		return web.TujuanPenetapanPemdaResponse{}, err
	}

	tujuans, err := s.Repo.FindTujuanPemdaBySnapshot(ctx, snapshot.Id, tahun)
	if err != nil {
		return web.TujuanPenetapanPemdaResponse{}, err
	}
	tujuanIDs := make([]int64, 0, len(tujuans))
	for _, tujuan := range tujuans {
		tujuanIDs = append(tujuanIDs, tujuan.Id)
	}

	indikators, err := s.Repo.FindIndikatorTujuanPemdaByTujuanIDs(ctx, tujuanIDs)
	if err != nil {
		return web.TujuanPenetapanPemdaResponse{}, err
	}
	indikatorIDs := make([]int64, 0, len(indikators))
	for _, indikator := range indikators {
		indikatorIDs = append(indikatorIDs, indikator.Id)
	}

	targets, err := s.Repo.FindTargetIndikatorTujuanPemdaByIndikatorIDs(ctx, indikatorIDs)
	if err != nil {
		return web.TujuanPenetapanPemdaResponse{}, err
	}

	targetMap := make(map[int64][]web.TargetPemdaResponse)
	for _, target := range targets {
		targetMap[target.IndikatorTujuanPemdaId] = append(
			targetMap[target.IndikatorTujuanPemdaId],
			web.TargetPemdaResponse{
				Id:         target.Id,
				KodeTarget: target.KodeTarget,
				Tahun:      target.Tahun,
				Target:     target.Target,
				Satuan:     target.Satuan,
			},
		)
	}

	indikatorMap := make(map[int64][]web.IndikatorPemdaPenetapanResponse)
	for _, indikator := range indikators {
		indikatorMap[indikator.IdTujuanPemda] = append(
			indikatorMap[indikator.IdTujuanPemda],
			web.IndikatorPemdaPenetapanResponse{
				Id:                  indikator.Id,
				KodeIndikator:       indikator.KodeIndikator,
				Indikator:           indikator.Indikator,
				RumusPerhitungan:    indikator.RumusPerhitungan,
				SumberData:          indikator.SumberData,
				DefinisiOperasional: indikator.DefinisiOperasional,
				TahunAktif:          indikator.TahunAktif,
				Target:              targetMap[indikator.Id],
			},
		)
	}

	response := make([]web.TujuanPemdaResponse, 0, len(tujuans))
	for _, tujuan := range tujuans {
		response = append(response, web.TujuanPemdaResponse{
			Id:              tujuan.Id,
			KodeTujuanPemda: tujuan.KodeTujuanPemda,
			Visi:            tujuan.Visi,
			Misi:            tujuan.Misi,
			TujuanPemda:     tujuan.TujuanPemda,
			Periode:         tujuan.Periode,
			Indikator:       indikatorMap[tujuan.Id],
		})
	}

	return web.TujuanPenetapanPemdaResponse{
		TahunAktif: tahun,
		Versi:      snapshot.Versi,
		IsLocked:   true,
		Tujuans:    response,
	}, nil
}

