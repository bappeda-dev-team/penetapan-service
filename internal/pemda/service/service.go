func (s *PenetapanPemdaService) markSyncAsFailed(ctx context.Context, syncId int64, msg string) error {
	statusSync := domain.SyncStatusFailed
	errorMessage := &msg
	return s.Repo.UpdateMetadataStatus(
		ctx,
		syncId,
		statusSync,
		errorMessage,
	)
}

func (s *PenetapanPemdaService) markSyncAsInProgress(ctx context.Context, syncId int64) error {
	statusSync := domain.SyncStatusInProgress
	return s.Repo.UpdateMetadataStatus(
		ctx,
		syncId,
		statusSync,
		nil,
	)
}

func (s *PenetapanPemdaService) markSyncAsSuccess(ctx context.Context, syncId int64) error {
	statusSync := domain.SyncStatusSuccess
	return s.Repo.UpdateMetadataStatus(
		ctx,
		syncId,
		statusSync,
		nil,
	)
}

func (s *PenetapanPemdaService) failSync(ctx context.Context, syncId int64, cause error) error {
	updateErr := s.markSyncAsFailed(
		ctx,
		syncId,
		cause.Error(),
	)
	if updateErr != nil {
		return updateErr
	}
	return cause
}

func (s *PenetapanPemdaService) FindTujuanSasaranPemda(
	ctx context.Context,
	tahun int,
) (web.TujuanSasaranPenetapanPemdaResponse, error) {
	tujuans, err := s.FindTujuanPemda(ctx, tahun)
	if err != nil {
		s.Logger.Error("FindTujuanPemda")
		return web.TujuanSasaranPenetapanPemdaResponse{}, err
	}

	sasarans, err := s.FindSasaranPemda(ctx, tahun)
	if err != nil {
		s.Logger.Error("FindSasaranPemda")
		return web.TujuanSasaranPenetapanPemdaResponse{}, err
	}

	sasaranMap := make(map[string][]web.SasaranPemdaResponse)

	for _, sasaran := range sasarans.Sasarans {
		sasaranMap[sasaran.KodeTujuanPemda] = append(
			sasaranMap[sasaran.KodeTujuanPemda],
			sasaran,
		)
	}

	response := make(
		[]web.TujuanWithSasaranPemdaResponse,
		0,
		len(tujuans.Tujuans),
	)
	for _, tujuan := range tujuans.Tujuans {
		response = append(response, web.TujuanWithSasaranPemdaResponse{
			Id:              tujuan.Id,
			KodeTujuanPemda: tujuan.KodeTujuanPemda,
			Visi:            tujuan.Visi,
			Misi:            tujuan.Misi,
			TujuanPemda:     tujuan.TujuanPemda,
			Periode:         tujuan.Periode,
			Indikator:       tujuan.Indikator,
			SasaranPemda:    sasaranMap[tujuan.KodeTujuanPemda],
		})
	}

	return web.TujuanSasaranPenetapanPemdaResponse{
		TahunAktif: tahun,
		Versi:      tujuans.Versi,
		IsLocked:   true,
		Tujuans:    response,
	}, nil
}
