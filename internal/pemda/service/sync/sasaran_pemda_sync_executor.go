func hasValidSasaranPemda(sasaranPemdas []client.SasaranPemdaPenetapanResponse) bool {
	for _, sasaran := range sasaranPemdas {
		if !helperPemda.IsValidSasaran(sasaran) {
			continue
		}

		for _, indikator := range sasaran.Indikator {
			if !helperPemda.IsValidIndikator(indikator) {
				continue
			}

			if slices.ContainsFunc(indikator.TargetPenetapan, helperPemda.IsValidTarget) {
				return true
			}
		}
	}

	return false
}
